int portMapFamily(const std::string& plugin, const std::string& model, bool isOutput, int port) {
	// ONLY NYSTHI SO FAR. The table is a list of readings of one maker's panels; every other
	// plugin either names its ports, in which case the rules decide, or has not been read.
	if (plugin != "NYSTHI")
		return -1;
	bool known = false;
	for (const Known& k : KNOWN) {
		if (model == k.model) {
			known = (portMapPortCount(plugin, model) == k.ports);
			break;
		}
	}
	if (!known)
		return -1;
	for (const Entry& e : ENTRIES) {
		if (e.out == isOutput && e.port == port && model == e.model)
			return e.family;
	}
	return -1;
}

